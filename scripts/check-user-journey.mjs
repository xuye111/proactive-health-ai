import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'vite'

const values = new Map()
globalThis.window = { localStorage: { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: (key) => values.delete(key) } }
const server = await createServer({ configFile: false, server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'error' })
try {
  const store = await server.ssrLoadModule('/src/lib/healthStore.ts')
  const { healthScore } = await server.ssrLoadModule('/src/lib/healthScore.ts')
  const { reviewPersonal, answerPersonalChat } = await server.ssrLoadModule('/src/ai/personal.ts')
  const { suggestSleepPlan, twoWeekSleepSummary } = await server.ssrLoadModule('/src/ai/sleepPlan.ts')
  const { companionSupport } = await server.ssrLoadModule('/src/ai/solutions.ts')
  const { parseConversationRecord } = await server.ssrLoadModule('/src/lib/conversationRecord.ts')
  const { createFollowUpFromSignal, confirmFollowUp, setFollowUpAction, recordFollowUpActionOutcome, assessFollowUp } = await server.ssrLoadModule('/src/ai/followUps.ts')

  const currentDate = store.localDate()
  assert.equal(store.activeRecord(store.getHealthState()).date, currentDate, 'one stream shows current local date')
  const prior = Array.from({ length: 7 }, (_, index) => {
    const day = new Date(`${currentDate}T12:00:00`)
    day.setDate(day.getDate() - (7 - index))
    return store.localDate(day)
  })
  for (const date of prior) store.saveDailyRecord(date, { sleepHours: 8, bedTime: '23:00', steps: 6000, activeMinutes: 30, energy: 4, stress: 2, mood: 4 })
  store.saveDailyRecord(currentDate, { sleepHours: 6, bedTime: '23:00', steps: 6000, activeMinutes: 30, energy: 4, stress: 2, mood: 4 })
  const history = store.effectiveRecords(store.getHealthState()).filter((record) => record.date < currentDate)
  const before = healthScore(store.activeRecord(store.getHealthState()), history, store.getHealthState().goals)
  assert.ok(before.score !== null)
  const review = reviewPersonal(store.getHealthState().records, currentDate)
  assert.ok(review.signals.some((signal) => signal.type === 'sleep_decline'))
  store.saveDailyRecord(currentDate, { sleepHours: 7.5 })
  const after = healthScore(store.activeRecord(store.getHealthState()), history, store.getHealthState().goals)
  assert.ok(after.score > before.score, 'editing one observation recomputes today score')
  let item = createFollowUpFromSignal(review.signals[0], `${currentDate}T10:00:00`)
  item = confirmFollowUp(item, `${currentDate}T10:01:00`)
  item = setFollowUpAction(item, '继续记录睡眠', `${currentDate}T10:02:00`, currentDate)
  item = recordFollowUpActionOutcome(item, '完成', undefined, `${currentDate}T10:03:00`, currentDate)
  assert.equal(item.status, '待回访')
  assert.equal(assessFollowUp(item, [], false).kind, 'missing_new_record', 'checking an action is not proof of effect')
  assert.equal(reviewPersonal([], currentDate, '胸痛').kind, 'escalation', 'safety wins without data')
  assert.deepEqual(parseConversationRecord('今天压力 3 分，精力 4 分，心情 2 分'), { energy: 4, stress: 3, mood: 2 }, 'conversation extracts only explicit values')
  assert.deepEqual(parseConversationRecord('今天压力很大'), {}, 'vague feelings do not become invented scale values')
  assert.equal(store.activeRecord(store.getHealthState()).sleepHours, 7.5, 'one stream retains user overrides')

  const proposed = suggestSleepPlan(store.effectiveRecords(store.getHealthState()), { wakeConstraint: '07:00' })
  assert.ok(proposed.target, 'recent nights and a wake constraint produce a reviewable goal')
  store.setSleepPreferences({ wakeConstraint: '07:00', acceptedTarget: proposed.target, acceptedAt: `${currentDate}T09:00:00` })
  assert.equal(suggestSleepPlan(store.effectiveRecords(store.getHealthState()), store.getHealthState().sleepPreferences).source, '已确认目标')
  store.markSleepPreparation(currentDate)
  store.markMorningFeedback(currentDate)
  assert.equal(store.getHealthState().sleepRoutine.preparationDoneOn, currentDate, 'preparation is recorded once for today')
  assert.equal(twoWeekSleepSummary(store.effectiveRecords(store.getHealthState()), currentDate, [], store.getHealthState().sleepRoutine.morningFeedbackHistory).reviewedMornings, 1, 'morning review is visible in the two-week summary')
  assert.equal(twoWeekSleepSummary(store.effectiveRecords(store.getHealthState()), currentDate, [], store.getHealthState().sleepRoutine.morningFeedbackHistory).personalNights, 0, 'confirmation does not turn incomplete or simulated nights into a personal model')
  const feedback = parseConversationRecord('记录昨晚刷手机')
  assert.equal(feedback.sleepBarrier, '使用手机', 'the same chat wording enters the record confirmation path')
  store.saveDailyRecord(currentDate, feedback)
  const updatedPlan = suggestSleepPlan(store.effectiveRecords(store.getHealthState()), store.getHealthState().sleepPreferences)
  assert.match(updatedPlan.action, /放下手机/, 'confirmed feedback changes the next action')
  const reply = answerPersonalChat(store.effectiveRecords(store.getHealthState()), currentDate, '我想改善作息', store.getHealthState().sleepPreferences)
  assert.match(reply.answer, new RegExp(proposed.target), 'XiaoMan uses the confirmed goal in the current user-facing reply')
  assert.equal(companionSupport('睡前总刷手机，怎么办', { acceptedTarget: proposed.target, sleepBarrier: '使用手机' })?.offerId, 'sleep-course', 'an expressed need may attach a related simulated plan')
  assert.equal(companionSupport('胸痛，推荐睡眠用品', { acceptedTarget: proposed.target }), null, 'safety context prevents a product card')
  // Source-level entry wiring checks; the state transitions are covered by the follow-up checks.
  const recordPage = await readFile(new URL('../src/pages/Record.tsx', import.meta.url), 'utf8')
  const homePage = await readFile(new URL('../src/pages/PersonalHome.tsx', import.meta.url), 'utf8')
  const panel = await readFile(new URL('../src/components/GoutFollowUpPanel.tsx', import.meta.url), 'utf8')
  assert.match(recordPage, /<GoutFollowUpPanel\b/, 'record tasks render the gout follow-up form')
  assert.match(homePage, /goutPrompt\(/, 'home evaluates a dated gout prompt')
  assert.match(homePage, /isGoutFollowUp\(item\)/, 'home routes gout items away from generic actions')
  assert.match(panel, /startPersonalGoutFollowUp\(/, 'form starts a persistent personal follow-up')
  assert.match(panel, /applyGoutEvent\(/, 'form feedback advances the gout state machine')
  console.log('user journey: 21 behavior checks and 5 source wiring checks passed')
} finally { await server.close() }
