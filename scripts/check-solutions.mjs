import assert from 'node:assert/strict'
import { createServer } from 'vite'

const server = await createServer({ configFile: false, server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'error' })
try {
  const { solutionContent, recognizeSupportIntent, companionSupport } = await server.ssrLoadModule('/src/ai/solutions.ts')
  const sleep = solutionContent('sleep_decline')
  assert.ok(sleep.step.includes('确认睡眠变化'))
  assert.ok(sleep.offers.some((item) => item.name === '睡眠习惯练习课'))
  assert.ok(!sleep.offers.some((item) => item.name === '压力管理练习课'))
  assert.ok(solutionContent().offers.length > 0, 'catalog remains browsable without a signal')
  assert.deepEqual(solutionContent('sleep_decline', true).offers, [], 'safety escalation suppresses all commerce')
  assert.equal(recognizeSupportIntent('今天压力很大'), null, 'health feedback alone does not trigger commerce')
  assert.equal(recognizeSupportIntent('推荐一些睡眠产品')?.topic, 'sleep')
  assert.equal(recognizeSupportIntent('睡前光线太亮，有什么遮光用品')?.topic, 'sleep')
  assert.equal(recognizeSupportIntent('想看看营养补充食品')?.topic, 'nutrition')
  assert.equal(recognizeSupportIntent('有没有适合的产品')?.topic, null, 'unclear topic must be confirmed')
  assert.equal(recognizeSupportIntent('胸痛，推荐一个产品'), null, 'red flag takes precedence over shopping intent')
  assert.equal(recognizeSupportIntent('有什么治疗失眠的保健品'), null, 'treatment intent does not lead to products')
  assert.equal(recognizeSupportIntent('我贫血，推荐营养补充品'), null, 'disease context does not lead to supplements')
  const nutrition = solutionContent(undefined, false, 'nutrition')
  assert.ok(nutrition.offers.some((item) => item.kind === '营养食品'))
  assert.ok(nutrition.offers.every((item) => item.kind !== '药品'))
  assert.deepEqual(solutionContent(undefined, true, 'nutrition').offers, [], 'safety still wins with explicit topic')
  assert.equal(companionSupport('我想改善作息', { acceptedTarget: '23:30', sleepBarrier: '使用手机' })?.offerId, 'sleep-course', 'expressed goal and user-provided barrier select a related course')
  assert.match(companionSupport('我想改善作息', { sleepBarrier: '使用手机' })?.reason ?? '', /此前记录了睡前使用手机/)
  assert.equal(companionSupport('睡前太亮，想找点办法')?.offerId, 'sleep-mask', 'light concern selects a non-medical item')
  assert.equal(companionSupport('睡前总刷手机，怎么办')?.offerId, 'sleep-course', 'a clear barrier and help request may show a non-medical practice')
  assert.equal(companionSupport('睡前光线太亮，有什么遮光用品')?.offerId, 'sleep-mask', 'ordinary help-seeking wording can open a relevant card')
  assert.equal(companionSupport('改善作息，有什么方案')?.offerId, 'sleep-course', 'goal request without 想 is recognized')
  assert.equal(companionSupport('我想了解适合我的睡眠方案')?.offerId, 'sleep-course', 'solution request is not limited to product vocabulary')
  assert.equal(companionSupport('推荐一些睡眠用品')?.offerId, 'sleep-mask', 'explicit shopping request remains supported')
  assert.equal(companionSupport('我想改善现在的状况', { personalSignal: 'activity_decline' })?.offerId, 'activity-coaching', 'personal signal helps resolve an otherwise generic goal')
  assert.equal(companionSupport('今天压力很大'), null, 'a health status statement alone does not trigger a product card')
  assert.equal(companionSupport('我想改善现在的状况'), null, 'simulated status alone cannot be treated as personal product evidence')
  assert.equal(companionSupport('我失眠了，想买点东西'), null, 'disease context suppresses commerce')
  assert.equal(companionSupport('胸痛，想改善睡眠'), null, 'red flags suppress commerce')
  assert.equal(companionSupport('我想改善作息', { safety: true }), null, 'an outstanding safety escalation suppresses the card')
  console.log('solutions: 30 checks passed')
} finally { await server.close() }
